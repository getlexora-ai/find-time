/**
 * Generates src/calendar/solar-icons.ts from @iconify-json/solar.
 *
 * Every glyph the reference mockup (design/from_user/calendar.html) uses is listed
 * below, keyed by the short name the app's <Icon name="…"> call sites already pass.
 * Run with: node scripts/gen-solar-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const set = JSON.parse(
  readFileSync(resolve(root, 'node_modules/@iconify-json/solar/icons.json'), 'utf8'),
);

/** app short name → exact `solar:` icon id used in calendar.html */
const MAP = {
  add: 'add-circle-linear',
  'arrow-down': 'alt-arrow-down-linear',
  'arrow-left': 'alt-arrow-left-linear',
  'arrow-right': 'alt-arrow-right-linear',
  // the plain (non-chevron) arrow — calendar.html moveRow()
  'arrow-forward': 'arrow-right-linear',
  'arrow-right-up': 'arrow-right-up-linear',
  bell: 'bell-linear',
  bolt: 'bolt-linear',
  bulb: 'lightbulb-bolt-linear',
  calendar: 'calendar-minimalistic-linear',
  'calendar-add': 'calendar-add-linear',
  chart: 'chart-2-linear',
  check: 'check-circle-linear',
  'check-bold': 'check-circle-bold',
  clock: 'clock-circle-linear',
  close: 'close-circle-linear',
  cup: 'cup-hot-linear',
  cursor: 'cursor-linear',
  dots: 'menu-dots-linear',
  eye: 'eye-linear',
  folder: 'folder-with-files-linear',
  magic: 'magic-stick-3-linear',
  mic: 'microphone-3-linear',
  palette: 'palette-linear',
  pen: 'pen-new-square-linear',
  refresh: 'refresh-circle-linear',
  search: 'magnifer-linear',
  shield: 'shield-check-linear',
  stars: 'stars-minimalistic-linear',
  sun: 'sun-2-linear',
  transfer: 'transfer-horizontal-linear',
  trash: 'trash-bin-trash-linear',
  triangle: 'danger-triangle-linear',
};

/** Follow Iconify aliases to a concrete icon. Transforms are not supported — none
 *  of the mockup's glyphs need one, so hitting a transformed alias is a hard error. */
function resolveIcon(id, seen = new Set()) {
  if (seen.has(id)) throw new Error(`alias cycle at "${id}"`);
  seen.add(id);
  if (set.icons[id]) return set.icons[id];
  const alias = set.aliases?.[id];
  if (!alias) throw new Error(`solar icon "${id}" not found in @iconify-json/solar`);
  for (const k of ['rotate', 'hFlip', 'vFlip', 'hiddenFlip']) {
    if (alias[k]) throw new Error(`alias "${id}" needs an unsupported transform: ${k}`);
  }
  return resolveIcon(alias.parent, seen);
}

const entries = Object.entries(MAP)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([short, id]) => {
    const icon = resolveIcon(id);
    if (icon.width && icon.width !== 24) throw new Error(`"${id}" is not 24-wide`);
    if (icon.height && icon.height !== 24) throw new Error(`"${id}" is not 24-tall`);
    if (!icon.body.includes('currentColor')) throw new Error(`"${id}" has no currentColor`);
    return { short, id, body: icon.body };
  });

const out = `// GENERATED by scripts/gen-solar-icons.mjs — do not edit by hand.
// Source: @iconify-json/solar (the exact glyphs design/from_user/calendar.html loads
// from cdn iconify as <iconify-icon icon="solar:…">). All 24x24, all currentColor.

/** Short name → Solar icon id, kept only for traceability back to calendar.html. */
export const SOLAR_ID = {
${entries.map((e) => `  '${e.short}': '${e.id}',`).join('\n')}
} as const;

export type IconName = keyof typeof SOLAR_ID;

/** Short name → the raw <svg> body of the Solar glyph. */
export const SOLAR_BODY: Record<IconName, string> = {
${entries.map((e) => `  '${e.short}': ${JSON.stringify(e.body)},`).join('\n')}
};
`;

writeFileSync(resolve(root, 'src/calendar/solar-icons.ts'), out);
console.log(`wrote src/calendar/solar-icons.ts — ${entries.length} icons`);
